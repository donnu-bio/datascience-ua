def _додати_аліаси(клас, відповідності):
    """
    Додає українські назви методів та властивостей класу.

    Копіює оригінальні дескриптори, зберігаючи поведінку
    звичайних методів, classmethod, staticmethod і property.
    """
    for українська, англійська in відповідності.items():
        # print(клас, англійська)
        дескриптор = inspect.getattr_static(клас, англійська)
        setattr(клас, українська, дескриптор)


